/** Advisory numeric check only: no interpretation of arbitrary prose or automatic rubric grade. */
export function numericCheck(text, key) {
  if (key.answer === null) return "해당 없음";
  let s = String(text).normalize("NFKC").replace(/,/g, "").replace(/\s/g, "");
  if (key.unit === "분" && /^1분30초$/.test(s)) s = "1.5";
  if (
    key.unit === "원" &&
    key.answer >= 50000 &&
    /^\d+(?:\.\d+)?$/.test(s) &&
    Number(s) < 1000
  )
    return "수동 확인";
  const m = s.match(
    /^([+−-]?\d+(?:\.\d+)?)\s*(만원|원|분|km\/h|km|킬로미터)?(?:이익)?$/i,
  );
  if (!m) return "수동 확인";
  const units = key.unit === "원" ? ["원", "만원"]
    : key.unit === "km" ? ["km", "킬로미터"] : [key.unit];
  if (m[2] && !units.includes(m[2].toLowerCase())) return "수동 확인";
  const n = Number(m[1].replace("−", "-")) * (m[2] === "만원" ? 10000 : 1);
  return Math.abs(n - key.answer) < 1e-9 ? "숫자 일치" : "숫자 불일치";
}
